# The ballet texts → the BALLET-DATA block of game/govorilki.html:
#  - stories/ballet/tales.json: «Сказки балета» (8 ballets in 2–4 chapters) — plain strings, translated by the build;
#  - stories/ballet/stories.json: ~25 knowledge stories, Russian only (LX('BALLET_STORIES'): {} in the other languages),
#    a section «Про балет» in LEARN;
#  - the names' and ballet words' stress → build/say_manual.json ('w' for words Russian does not otherwise have,
#    'cap' for names that are also common words).
import json, os, re
B = os.path.dirname(os.path.abspath(__file__)); S = os.path.join(B, '..', 'stories', 'ballet')
tales = json.load(open(os.path.join(S, 'tales.json'), encoding='utf-8'))
sp = os.path.join(S, 'stories.json')
st = json.load(open(sp, encoding='utf-8')) if os.path.exists(sp) else {'ballet': [], 'stress': {}}
T = []
for t in tales['tales']:
    assert re.fullmatch(r'[a-z]+', t['id']) and 2 <= len(t['ch']) <= 4 and len(t['a']) == 3, t['id']
    for c in t['ch']:
        if not 300 <= len(c['s']) <= 700 or "'" in c['s']: print(' ! tale', t['id'], c['t'], len(c['s']))
    T.append({k: t[k] for k in ('id', 't', 'by', 'y', 'e', 'sub', 'ch', 'q', 'a')})
items, ids = [], set()
for x in st['ballet']:
    assert set(x) >= {'id', 'e', 't', 's', 'q', 'a'} and len(x['a']) == 3 and re.fullmatch(r'[a-z0-9-]+', x['id']) and x['id'] not in ids, x.get('id')
    ids.add(x['id'])
    if not 250 <= len(x['s']) <= 650 or "'" in json.dumps(x, ensure_ascii=False): print(' ! story', x['id'], len(x['s']))
    items.append({k: x[k] for k in ('id', 'e', 't', 's', 'q', 'a')})
G = os.path.join(B, '..', 'game', 'govorilki.html'); g = open(G, encoding='utf-8').read()
for x in items: assert g.count(f'"id": "{x["id"]}"') == g.count(f'"id":"{x["id"]}"') == 0 or '/* BALLET-DATA-BEGIN */' in g, x['id']
part = ("/* ---------- generated by build/gen_ballet.py from stories/ballet/*.json: the tales (translated by the build) and the\n"
        "   knowledge stories (Russian only) ---------- */\n"
        "const BALLET_TALES = " + json.dumps(T, ensure_ascii=False) + ";\n"
        "const BALLET_STORIES = LX('BALLET_STORIES', " + json.dumps({'name': 'Про балет', 'sub': 'пуанты, пачки, театры и великие танцовщики', 'items': items} if items else {}, ensure_ascii=False) + ");\n"
        "if (BALLET_STORIES.items) LEARN.ballet = { name: BALLET_STORIES.name, e: '🩰', bg: 'var(--t-pink)', sub: BALLET_STORIES.sub, items: BALLET_STORIES.items };\n")
a = g.index('/* BALLET-DATA-BEGIN */\n') + len('/* BALLET-DATA-BEGIN */\n'); b = g.index('/* BALLET-DATA-END */\n', a)
open(G, 'w', encoding='utf-8').write(g[:a] + part + g[b:])
I = os.path.join(B, '..', 'i18n')
for p in ['phonics/C.en.json', 'phonics/C.pt.json', 'de/langdata_de.json']:
    p = os.path.join(I, p); x = json.load(open(p, encoding='utf-8')); x['BALLET_STORIES'] = {}
    json.dump(x, open(p, 'w', encoding='utf-8'), ensure_ascii=False)
# stress: names that are also common Russian words are marked only when capitalised
COMMON = {'аврора', 'авроры', 'аврору', 'авроре', 'мавр', 'мавра', 'мавром', 'петрушка', 'петрушки', 'петрушку', 'петрушке', 'петрушкой',
          'сирени', 'сирень', 'масленица', 'масленицу', 'масленицы', 'павлова', 'павловой', 'павлову', 'бал', 'фея', 'лебедь'}
SKIP = {'балерина', 'балерины', 'балерину', 'балерине', 'лебединое', 'лебединого', 'драже', 'петербург', 'петербурге', 'золушка', 'золушки', 'золушку', 'золушке', 'золушкой'}
TERMS = {'плие': 'пли+е', 'релеве': 'релев+е', 'тандю': 'танд+ю', 'батман': 'батм+ан', 'арабеск': 'араб+еск', 'пируэт': 'пиру+эт', 'пируэта': 'пиру+эта',
         'пируэты': 'пиру+эты', 'пуанты': 'пу+анты', 'пуантах': 'пу+антах', 'пуантов': 'пу+антов', 'пуанты.': None, 'фуэте': 'фуэт+е', 'кордебалет': 'кордебал+ет'}
man = json.load(open(B + '/say_manual.json', encoding='utf-8')); n = 0
stress = {**tales.get('stress', {}), **st.get('stress', {})}
stress.update({k: v for k, v in TERMS.items() if v})
for w, f in stress.items():
    w, f = w.lower(), f.lower()
    if not re.fullmatch(r'[а-яё-]+', w) or f.replace('+', '') != w or f.count('+') < 1: continue
    for part, pf in zip(w.split('-'), f.split('-')):
        if '+' not in pf or len([c for c in part if c in 'аеёиоуыэюя']) < 2 or part in SKIP: continue
        if part in man['w'] or part in man['cap']: continue
        man['cap' if part in COMMON else 'w'][part] = pf; n += 1
json.dump(man, open(B + '/say_manual.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('ballet tales:', len(T), 'stories:', len(items), 'stress added:', n)
