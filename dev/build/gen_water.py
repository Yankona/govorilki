# The water stories (Russian only) in stories/water/water.json → the WATER block of game/govorilki.html: a section
# «Моря, реки и озёра» in LEARN; the other languages get WATER_STORIES = {} from their langdata, so the section is not there
import json, os, re
B = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(B, '..', 'stories', 'water', 'water.json'), encoding='utf-8'))
items = []
for x in d['water']:
    assert set(x) >= {'id', 'e', 't', 's', 'q', 'a'} and len(x['a']) == 3 and re.fullmatch(r'[a-z0-9-]+', x['id']), x.get('id')
    if not 250 <= len(x['s']) <= 650 or "'" in json.dumps(x, ensure_ascii=False): print(' !', x['id'])
    items.append({k: x[k] for k in ('id', 'e', 't', 's', 'q', 'a')})
assert len({x['id'] for x in items}) == len(items)
part = ("/* ---------- «Моря, реки и озёра»: knowledge stories about water (Russian only; generated by build/gen_water.py "
        "from stories/water/water.json) ---------- */\n"
        "const WATER_STORIES = LX('WATER_STORIES', " + json.dumps({'name': 'Моря, реки и озёра', 'sub': 'волны, приливы, Волга, Байкал, Амазонка', 'items': items}, ensure_ascii=False) + ");\n"
        "if (WATER_STORIES.items) LEARN.water = { name: WATER_STORIES.name, e: '🌊', bg: 'var(--t-blue)', sub: WATER_STORIES.sub, items: WATER_STORIES.items };\n")
G = os.path.join(B, '..', 'game', 'govorilki.html'); g = open(G, encoding='utf-8').read()
a = g.index('/* WATER-BEGIN */\n') + len('/* WATER-BEGIN */\n'); b = g.index('/* WATER-END */\n', a)
open(G, 'w', encoding='utf-8').write(g[:a] + part + g[b:])
T = os.path.join(B, '..', 'i18n')
for p in ['phonics/C.en.json', 'phonics/C.pt.json', 'de/langdata_de.json']:
    p = os.path.join(T, p); x = json.load(open(p, encoding='utf-8')); x['WATER_STORIES'] = {}
    json.dump(x, open(p, 'w', encoding='utf-8'), ensure_ascii=False)
print('water stories:', len(items))
