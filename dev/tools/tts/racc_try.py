import sys
from ruaccent import RUAccent
a = RUAccent()
a.load(omograph_model_size='turbo3.1', use_dictionary=True, workdir=sys.argv[1])
for t in ['Здорово! Ты всё сделал.', 'Здорово, Вера!', 'Лев не нападает, всё замерло.', 'Я уже иду.', 'Иди дорогой через лес, мой дорогой друг.', 'Лев Толстой написал', 'Бах играл на органе.', 'В замке был старинный замок на двери.', 'Все звёзды твои!', 'Ты собрал все буквы!', 'Музыкальная шкатулка играет мелодию.']:
    print(t, '→', a.process_all(t))
